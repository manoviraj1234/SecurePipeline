"""
Scans Router for SecurePipeline API.
Provides endpoints for listing, viewing, and ingesting security reports.
"""

import json
from pathlib import Path
from typing import Annotated, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from ..database import get_db
from .. import crud, schemas
from ..security import verify_api_key
from ..regression import calculate_scan_regression

router = APIRouter(prefix="/scans", tags=["Scans"])


@router.get("", response_model=schemas.ScanListResponse)
def list_scans(
    skip: Annotated[int, Query(ge=0)] = 0,
    limit: Annotated[int, Query(ge=1, le=100)] = 20,
    gate_decision: Optional[str] = None,
    db: Session = Depends(get_db),
):
    """Retrieves paginated scan history with optional gate decision filtering."""
    scans, total = crud.get_scans(db, skip=skip, limit=limit, gate_decision=gate_decision)
    return schemas.ScanListResponse(
        total=total,
        page=(skip // limit) + 1,
        page_size=limit,
        scans=[schemas.ScanSummaryOut.model_validate(s) for s in scans],
    )


@router.get("/{scan_id}", response_model=schemas.ScanDetailOut)
def get_scan(
    scan_id: int,
    db: Session = Depends(get_db),
):
    """Retrieves complete details of a specific security scan by ID."""
    scan = crud.get_scan_by_id(db, scan_id=scan_id)
    if not scan:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Scan with ID {scan_id} not found.",
        )
    return scan


@router.get("/{scan_id}/regression")
def get_scan_regression(
    scan_id: int,
    db: Session = Depends(get_db),
):
    """Computes security regression analysis comparing this scan with the previous one."""
    return calculate_scan_regression(db, current_scan_id=scan_id)


@router.post("/ingest", response_model=schemas.ScanDetailOut, status_code=status.HTTP_201_CREATED)
def ingest_scan_report(
    report: schemas.SecurityReportIngest,
    authorized: bool = Depends(verify_api_key),
    db: Session = Depends(get_db),
):
    """
    Ingests a complete security report generated by Phase 4.
    Atomically stores the scan, findings, and scanner statuses.
    """
    try:
        new_scan = crud.create_scan_from_report(db, report=report)
        return crud.get_scan_by_id(db, scan_id=new_scan.id)
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=str(exc),
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Failed to ingest scan report: {str(exc)}",
        )


@router.post("/ingest-file", response_model=schemas.ScanDetailOut, status_code=status.HTTP_201_CREATED)
def ingest_scan_report_from_file(
    file_path: str = Query("reports/security_report.json", description="Relative or absolute path to JSON report file"),
    authorized: bool = Depends(verify_api_key),
    db: Session = Depends(get_db),
):
    """Helper endpoint to ingest a report directly from a local file on disk."""
    reports_dir = (Path(__file__).resolve().parents[2] / "reports").resolve()
    requested_path = Path(file_path)
    # Resolve symlinks and reject traversal and absolute paths outside reports/.
    report_path = (reports_dir.parent / requested_path).resolve()
    if not report_path.is_relative_to(reports_dir) or report_path.suffix.lower() != ".json":
        raise HTTPException(status_code=403, detail="Only JSON files inside the backend reports directory are allowed.")
    if not report_path.is_file():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Report file not found at: {file_path}",
        )

    try:
        with report_path.open("r", encoding="utf-8") as f:
            raw_data = json.load(f)
        validated_report = schemas.SecurityReportIngest.model_validate(raw_data)
        new_scan = crud.create_scan_from_report(db, report=validated_report, raw_payload=raw_data)
        return crud.get_scan_by_id(db, scan_id=new_scan.id)
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=str(exc),
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Error reading or parsing report file: {str(exc)}",
        )
